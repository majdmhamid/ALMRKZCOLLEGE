/** What the page texts need from «معلومات الكلية». */
function context(shared: Shared, locale: SiteLocale): Ctx {
  const s = shared.settings
  const fallbackName = locale === 'he' ? 'מכללת המרכז להכשרה מקצועית – אום אל-פחם' : 'كلية المركز للتأهيل المهني – أم الفحم'
  return {
    months: leadRetentionMonths(s.privacy?.leadsRetentionMonths),
    auditDate: s.accessibility?.auditDate?.slice(0, 10) || LEGAL_UPDATED.accessibility,
    college: s.siteName || fallbackName,
    privacyEmail: s.privacy?.contactEmail || s.contact?.email || '',
    analytics: Boolean(GA_ID || META_PIXEL_ID),
  }
}

const linkStyle: React.CSSProperties = {
  color: '#0f6b33',
  fontWeight: 700,
  textDecoration: 'underline',
  textUnderlineOffset: 3,
}

type Row = { key: string; label: string; value: React.ReactNode }

const phoneRow = (label: string, phone: string): Row => ({
  key: 'phone',
  label,
  value: (
    <a href={telHref(phone)} dir="ltr" style={linkStyle}>
      {phone}
    </a>
  ),
})
const emailRow = (label: string, email: string): Row => ({
  key: 'email',
  label,
  value: (
    <a href={`mailto:${email}`} dir="ltr" style={{ ...linkStyle, wordBreak: 'break-all' }}>
      {email}
    </a>
  ),
})

function Rows({ rows }: { rows: Row[] }) {
  if (!rows.length) return null
  return (
    <ul className="facts-list" style={{ marginTop: 10 }}>
      {rows.map((r) => (
        <li key={r.key} style={{ flexWrap: 'wrap' }}>
          <span>{r.label}</span>
          <b>{r.value}</b>
        </li>
      ))}
    </ul>
  )
}

/** The college's phone / email / address from site settings. */
function ContactList({ shared, locale }: { shared: Shared; locale: SiteLocale }) {
  const t = UI[locale]
  const contact = shared.settings.contact
  const phone = contact?.phones?.[0]?.number
  const rows: Row[] = []
  if (phone) rows.push(phoneRow(t.phone, phone))
  if (contact?.email) rows.push(emailRow(t.email, contact.email))
  if (contact?.address) rows.push({ key: 'address', label: t.address, value: contact.address })
  return <Rows rows={rows} />
}

/**
 * The accessibility coordinator (רכז נגישות) from site settings — name, role, phone, email.
 * Until the college fills it in, the general contact details are shown instead.
 */
function Coordinator({ shared, locale }: { shared: Shared; locale: SiteLocale }) {
  const t = UI[locale]
  const a = shared.settings.accessibility
  if (!a?.coordinatorName && !a?.coordinatorPhone && !a?.coordinatorEmail)
    return <ContactList shared={shared} locale={locale} />
  const rows: Row[] = []
  if (a.coordinatorName)
    rows.push({
      key: 'name',
      label: a.coordinatorRole || (locale === 'he' ? 'רכז/ת נגישות' : 'ممثّل/ة الوصولية'),
      value: a.coordinatorName,
    })
  if (a.coordinatorPhone) rows.push(phoneRow(t.phone, a.coordinatorPhone))
  if (a.coordinatorEmail) rows.push(emailRow(t.email, a.coordinatorEmail))
  return <Rows rows={rows} />
}

/** Building accessibility (one bullet per line typed in site settings). */
function Building({ shared, locale }: { shared: Shared; locale: SiteLocale }) {
  const lines = (shared.settings.accessibility?.building ?? '')
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean)
  if (!lines.length) return null
  return (
    <>
      <p className="prose" style={{ marginTop: 14, fontWeight: 800 }}>
        {UI[locale].building}
      </p>
      <ul className="prose" style={{ margin: '6px 0 0', paddingInlineStart: 22 }}>
        {lines.map((l) => (
          <li key={l} style={{ marginTop: 6 }}>
            {l}
          </li>
        ))}
      </ul>
    </>
  )
}

